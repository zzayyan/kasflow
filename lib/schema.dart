import 'package:powersync/powersync.dart';

// On-device SQLite mirror of supabase/migrations/0001_init.sql.
// PowerSync adds the `id` column itself. Postgres types map to:
// bigint/boolean -> integer (booleans are 0/1), jsonb/timestamptz/date/uuid -> text.
const schema = Schema([
  Table('user_settings', [
    Column.text('user_id'),
    Column.text('base_currency'),
    Column.text('created_at'),
    Column.text('updated_at'),
  ]),
  Table('accounts', [
    Column.text('user_id'),
    Column.text('name'),
    Column.text('type'),
    Column.text('provider'),
    Column.text('currency'),
    Column.integer('initial_balance'),
    Column.text('color'),
    Column.integer('archived'),
    Column.integer('exclude_from_stats'),
    Column.text('created_at'),
    Column.text('updated_at'),
  ]),
  Table('categories', [
    Column.text('user_id'),
    Column.text('parent_id'),
    Column.text('name'),
    Column.text('type'),
    Column.text('need_level'),
    Column.text('keywords'),
    Column.text('color'),
    Column.text('icon'),
    Column.integer('archived'),
    Column.text('created_at'),
    Column.text('updated_at'),
  ]),
  Table('labels', [
    Column.text('user_id'),
    Column.text('name'),
    Column.text('color'),
    Column.text('created_at'),
    Column.text('updated_at'),
  ]),
  Table(
    'records',
    [
      Column.text('user_id'),
      Column.text('account_id'),
      Column.text('type'),
      Column.integer('amount'),
      Column.text('currency'),
      Column.text('category_id'),
      Column.text('transfer_account_id'),
      Column.integer('transfer_amount'),
      Column.text('label_ids'),
      Column.text('note'),
      Column.text('payee'),
      Column.text('place'),
      Column.text('photo_path'),
      Column.text('occurred_at'),
      Column.text('status'),
      Column.text('source'),
      Column.text('source_ref'),
      Column.text('planned_payment_id'),
      Column.text('created_at'),
      Column.text('updated_at'),
    ],
    indexes: [
      Index('by_time', [IndexedColumn.descending('occurred_at')]),
    ],
  ),
  Table('budgets', [
    Column.text('user_id'),
    Column.text('name'),
    Column.text('period'),
    Column.integer('amount'),
    Column.text('currency'),
    Column.text('start_date'),
    Column.text('end_date'),
    Column.text('category_ids'),
    Column.text('account_ids'),
    Column.text('label_ids'),
    Column.text('created_at'),
    Column.text('updated_at'),
  ]),
  Table('goals', [
    Column.text('user_id'),
    Column.text('name'),
    Column.integer('target_amount'),
    Column.text('currency'),
    Column.text('account_id'),
    Column.text('target_date'),
    Column.text('state'),
    Column.text('color'),
    Column.text('note'),
    Column.text('created_at'),
    Column.text('updated_at'),
  ]),
  Table('planned_payments', [
    Column.text('user_id'),
    Column.text('name'),
    Column.text('account_id'),
    Column.text('category_id'),
    Column.text('type'),
    Column.integer('amount'),
    Column.text('currency'),
    Column.text('rrule'),
    Column.text('next_due_date'),
    Column.integer('remind_days_before'),
    Column.text('note'),
    Column.text('created_at'),
    Column.text('updated_at'),
  ]),
  Table('exchange_rates', [Column.text('rate_date'), Column.text('currency'), Column.text('per_usd')]),
  // B1: transactions detected in bank/e-wallet notifications, waiting for the user to
  // confirm; amount NULL means Gemini has not read it yet. Local-only: the raw text stays on
  // the phone, and only a redacted copy goes to Gemini (lib/notifications.dart).
  Table.localOnly('inbox', [
    Column.text('ref'),
    Column.text('package'),
    Column.text('provider'),
    Column.text('title'),
    Column.text('text'),
    Column.integer('amount'),
    Column.text('type'),
    Column.text('posted_at'),
  ]),
  // Uploads the server rejected for good (constraint or RLS errors). Kept on the
  // device instead of being dropped, so a bug never silently loses a transaction.
  Table.localOnly('upload_errors', [
    Column.text('table_name'),
    Column.text('op'),
    Column.text('row_id'),
    Column.text('data'),
    Column.text('error'),
    Column.text('created_at'),
  ]),
  // Preferences of this phone (hide balance, reminder time), keyed by id. Never synced.
  Table.localOnly('prefs', [Column.text('value')]),
]);
